#!/bin/bash
# Stage the three ladder-pinned GGUFs into the spike bucket WITHOUT crossing the laptop uplink: a
# CodeBuild ARM job downloads each file from Hugging Face, checks its sha256 against the capability
# ladder's pin, and copies it to S3 (021 lesson: never move multi-GB artifacts over the ~3.7 MB/s uplink).
#   bash tools/fetch_weights_codebuild.sh            # create role + project (idempotent), start, poll, print log tail
set -uo pipefail
P="${AWS_PROFILE_NAME:-ze-kasher-dev}"; R=us-east-1; N=llm-spike-031
aws() { command aws --profile "$P" --region "$R" "$@"; }
A=$(aws sts get-caller-identity --query Account --output text) || exit 1
B="$N-$A"; ROLE="$N-codebuild"; PROJ="$N-fetch-weights"

aws iam get-role --role-name "$ROLE" >/dev/null 2>&1 || aws iam create-role --role-name "$ROLE" --tags Key=spike,Value=031 \
  --assume-role-policy-document '{"Version":"2012-10-17","Statement":[{"Effect":"Allow","Principal":{"Service":"codebuild.amazonaws.com"},"Action":"sts:AssumeRole"}]}' >/dev/null
aws iam put-role-policy --role-name "$ROLE" --policy-name s3-logs --policy-document "{\"Version\":\"2012-10-17\",\"Statement\":[
 {\"Effect\":\"Allow\",\"Action\":[\"s3:PutObject\",\"s3:AbortMultipartUpload\",\"s3:ListBucket\",\"s3:GetObject\",\"s3:ListMultipartUploadParts\"],\"Resource\":[\"arn:aws:s3:::$B\",\"arn:aws:s3:::$B/*\"]},
 {\"Effect\":\"Allow\",\"Action\":[\"logs:CreateLogGroup\",\"logs:CreateLogStream\",\"logs:PutLogEvents\"],\"Resource\":\"*\"}]}"
sleep 8  # IAM propagation before CodeBuild assumes the role

read -r -d '' BUILDSPEC <<'EOF'
version: 0.2
phases:
  build:
    commands:
      - |
        set -e
        fetch() { # repo file pin  (one shell: CodeBuild runs each list entry in its own shell)
          T0=$(date +%s)
          curl -sSL --retry 5 --retry-delay 5 -o "$2" "https://huggingface.co/$1/resolve/main/$2"
          echo "DOWNLOAD $2 $(( $(date +%s)-T0 ))s $(stat -c %s "$2") bytes"
          SHA=$(sha256sum "$2" | cut -d' ' -f1); echo "SHA256 $2 $SHA"
          [ "$SHA" = "$3" ] || { echo "SHA MISMATCH for $2: want $3"; exit 9; }
          T1=$(date +%s); aws s3 cp "$2" "s3://$BUCKET/$2" --only-show-errors --metadata sha256=$SHA; echo "UPLOAD $2 $(( $(date +%s)-T1 ))s"
          rm -f "$2"
        }
        fetch unsloth/Qwen3.5-0.8B-GGUF Qwen3.5-0.8B-Q4_K_M.gguf bd258782e35f7f458f8aced1adc053e6e92e89bc735ba3be89d38a06121dc517
        fetch unsloth/Qwen3.5-2B-GGUF Qwen3.5-2B-Q4_K_M.gguf aaf42c8b7c3cab2bf3d69c355048d4a0ee9973d48f16c731c0520ee914699223
        fetch unsloth/Qwen3.5-4B-GGUF Qwen3.5-4B-Q4_K_M.gguf 00fe7986ff5f6b463e62455821146049db6f9313603938a70800d1fb69ef11a4
        aws s3 ls "s3://$BUCKET/"
EOF

# The project JSON is generated by python so the multi-line buildspec survives quoting intact.
python3 - "$PROJ" "arn:aws:iam::$A:role/$ROLE" "$B" "$BUILDSPEC" > /tmp/llm-spike-031-codebuild.json <<'PY'
import json, sys
name, role, bucket, spec = sys.argv[1:5]
print(json.dumps({"name": name, "serviceRole": role, "tags": [{"key": "spike", "value": "031"}],
  "source": {"type": "NO_SOURCE", "buildspec": spec}, "artifacts": {"type": "NO_ARTIFACTS"},
  "environment": {"type": "ARM_CONTAINER", "image": "aws/codebuild/amazonlinux-aarch64-standard:3.0", "computeType": "BUILD_GENERAL1_SMALL",
                  "environmentVariables": [{"name": "BUCKET", "value": bucket}]},
  "timeoutInMinutes": 30}))
PY
if aws codebuild batch-get-projects --names "$PROJ" --query 'projects[0].name' --output text 2>/dev/null | grep -q "$PROJ"; then
  aws codebuild update-project --cli-input-json file:///tmp/llm-spike-031-codebuild.json >/dev/null || exit 1
else
  aws codebuild create-project --cli-input-json file:///tmp/llm-spike-031-codebuild.json >/dev/null || exit 1
fi
BID=$(aws codebuild start-build --project-name "$PROJ" --query 'build.id' --output text) || exit 1
echo "build $BID started"
for _ in $(seq 1 180); do
  ST=$(aws codebuild batch-get-builds --ids "$BID" --query 'builds[0].buildStatus' --output text)
  [ "$ST" != "IN_PROGRESS" ] && break
  sleep 10
done
echo "build status: $ST"
LG=$(aws codebuild batch-get-builds --ids "$BID" --query 'builds[0].logs.[groupName,streamName]' --output text)
set -- $LG
aws logs get-log-events --log-group-name "$1" --log-stream-name "$2" --start-from-head --query 'events[].message' --output text 2>/dev/null \
  | grep -E 'DOWNLOAD|SHA|UPLOAD|MISMATCH|rror|gguf' | head -30
echo "FETCH $ST"
